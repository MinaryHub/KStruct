"""Build KStruct with an ever-increasing version number.

    uv run python packaging/build.py            # stamp, freeze, self-test, package
    uv run python packaging/build.py --stamp    # only write the build stamp
    uv run python packaging/build.py --number 57  # use this build number (CI: run number)

The version is RELEASE_VERSION (pyproject.toml / kstruct.__init__) plus a fourth
component, the build number. Without --number or the KSTRUCT_BUILD_NUMBER variable the
number comes from packaging/build_number.txt, which is incremented and saved on every
build (commit it to keep the sequence shared between machines). The stamp lands in
src/kstruct/_build.py (ignored by git) and is frozen into the app, so the About dialog,
the log file, the PDF report and the installer file name all show e.g. 0.1.0.57.
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import platform
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COUNTER = ROOT / "packaging" / "build_number.txt"
STAMP = ROOT / "src" / "kstruct" / "_build.py"


def release_version(root: Path = ROOT) -> str:
    pyproject = tomllib.loads((root / "pyproject.toml").read_text("utf-8"))
    return pyproject["project"]["version"]


def next_build_number(counter: Path = COUNTER, explicit: int | None = None) -> int:
    """Explicit number (argument or KSTRUCT_BUILD_NUMBER) or the counter file + 1."""
    if explicit is None and os.environ.get("KSTRUCT_BUILD_NUMBER"):
        explicit = int(os.environ["KSTRUCT_BUILD_NUMBER"])
    if explicit is not None:
        if explicit < 1:
            raise SystemExit("build number must be 1 or more")
        return explicit
    current = int(counter.read_text("utf-8").strip() or 0) if counter.is_file() else 0
    number = current + 1
    counter.write_text(f"{number}\n", "utf-8")
    return number


def git_commit(root: Path = ROOT) -> str:
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def write_stamp(number: int, stamp: Path = STAMP, commit: str | None = None) -> str:
    """Write kstruct/_build.py and return the full version string."""
    date = dt.date.today().isoformat()
    commit = git_commit() if commit is None else commit
    stamp.write_text(
        "# Generated by packaging/build.py; not committed. Delete to run as the plain release.\n"
        f"BUILD_NUMBER = {number}\n"
        f'BUILD_DATE = "{date}"\n'
        f'GIT_COMMIT = "{commit}"\n',
        "utf-8",
    )
    return f"{release_version(stamp.parents[2])}.{number}"


def run(*cmd: str, cwd: Path = ROOT) -> None:
    print("+", " ".join(cmd), flush=True)
    subprocess.run(list(cmd), cwd=cwd, check=True)


def frozen_binary() -> Path:
    if sys.platform == "darwin":
        return ROOT / "dist" / "KStruct.app" / "Contents" / "MacOS" / "KStruct"
    if sys.platform == "win32":
        return ROOT / "dist" / "KStruct" / "KStruct.exe"
    return ROOT / "dist" / "KStruct" / "KStruct"


def package(version: str) -> list[Path]:
    """Installer / archive named after the version. Returns the files made."""
    dist = ROOT / "dist"
    if sys.platform == "win32":
        iscc = shutil.which("iscc") or r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"
        if not Path(iscc).is_file():
            print("Inno Setup (iscc) not found: skipping the installer", file=sys.stderr)
            return []
        run(iscc, f"/DAppVersion={version}", str(ROOT / "packaging" / "windows" / "kstruct.iss"))
        return [dist / f"KStruct-Setup-{version}.exe"]
    if sys.platform == "darwin":
        out = dist / f"KStruct-{version}-macOS.dmg"
        run(
            "hdiutil",
            "create",
            "-volname",
            "KStruct",
            "-srcfolder",
            str(dist / "KStruct.app"),
            "-ov",
            "-format",
            "UDZO",
            str(out),
        )
        return [out]
    out = dist / f"KStruct-{version}-linux-{platform.machine()}.tar.gz"
    run("tar", "-C", str(dist), "-czf", str(out), "KStruct")
    return [out]


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--number", type=int, help="build number to use instead of the counter")
    parser.add_argument("--stamp", action="store_true", help="only write src/kstruct/_build.py")
    parser.add_argument("--no-package", action="store_true", help="freeze but skip the installer")
    parser.add_argument("--no-selftest", action="store_true", help="skip the frozen app self-test")
    args = parser.parse_args()

    version = write_stamp(next_build_number(explicit=args.number))
    print(f"KStruct version {version}")
    if args.stamp:
        return 0
    run(
        sys.executable,
        "-m",
        "PyInstaller",
        str(ROOT / "packaging" / "kstruct.spec"),
        "--noconfirm",
        "--log-level",
        "WARN",
    )
    binary = frozen_binary()
    if not args.no_selftest:
        run(str(binary), "--version")
        run(str(binary), "--selftest")
    if not args.no_package:
        for f in package(version):
            print(f"built {f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
